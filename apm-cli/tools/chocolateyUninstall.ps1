$ErrorActionPreference = 'Stop'

$packageVersion = $env:ChocolateyPackageVersion
$installRoot = if ($env:LOCALAPPDATA) { Join-Path $env:LOCALAPPDATA 'Programs\apm' } else { $null }

if (-not $installRoot) {
    Write-Warning 'LOCALAPPDATA is not available; leaving the per-user APM files unchanged.'
    return
}

$releaseDir = Join-Path $installRoot "releases\chocolatey-$packageVersion"
$releaseMarker = Join-Path $releaseDir 'apm-cli-chocolatey.version'
$currentDir = Join-Path $installRoot 'current'
$binDir = Join-Path $installRoot 'bin'
$shimPath = Join-Path $binDir 'apm.cmd'
$ownsRelease = (Test-Path -LiteralPath $releaseMarker -PathType Leaf) -and
    (Get-Content -LiteralPath $releaseMarker -Raw).Trim() -eq $packageVersion
$ownsCurrent = $false

if ($ownsRelease -and (Test-Path -LiteralPath $currentDir)) {
    $currentMarker = Join-Path $currentDir 'apm-cli-chocolatey.version'
    $ownsCurrent = (Test-Path -LiteralPath $currentMarker -PathType Leaf) -and
        (Get-Content -LiteralPath $currentMarker -Raw).Trim() -eq $packageVersion
}

if ($ownsCurrent) {
    $currentItem = Get-Item -LiteralPath $currentDir -Force
    if (($currentItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0) {
        throw "Refusing to remove non-junction APM path: $currentDir"
    }
    [IO.Directory]::Delete($currentDir)

    if (Test-Path -LiteralPath $shimPath -PathType Leaf) {
        $shimContent = Get-Content -LiteralPath $shimPath -Raw
        if ($shimContent -match '(?m)^REM Generated by the apm-cli Chocolatey package\.\r?$') {
            Remove-Item -LiteralPath $shimPath -Force
        }
    }

    Uninstall-ChocolateyPath -Path $currentDir -PathType User
    Uninstall-ChocolateyPath -Path $binDir -PathType User
}

if ($ownsRelease) {
    Remove-Item -LiteralPath $releaseDir -Recurse -Force
} else {
    Write-Warning "No apm-cli-owned release was found for version $packageVersion; leaving release files unchanged."
}

foreach ($directory in @((Join-Path $installRoot 'releases'), $binDir, $installRoot)) {
    if ((Test-Path -LiteralPath $directory -PathType Container) -and
        -not (Get-ChildItem -LiteralPath $directory -Force | Select-Object -First 1)) {
        Remove-Item -LiteralPath $directory -Force
    }
}
