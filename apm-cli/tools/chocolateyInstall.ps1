$ErrorActionPreference = 'Stop'
$toolsDir = "$(Split-Path -Parent $MyInvocation.MyCommand.Definition)"

$packageVersion = $env:ChocolateyPackageVersion
$archivePath = Join-Path $toolsDir 'apm-windows-x86_64.zip'
$processorArchitecture = if ($env:PROCESSOR_ARCHITEW6432) {
    $env:PROCESSOR_ARCHITEW6432
} else {
    $env:PROCESSOR_ARCHITECTURE
}

if (-not [Environment]::Is64BitOperatingSystem -or $processorArchitecture -ne 'AMD64') {
    throw "$env:ChocolateyPackageName supports Windows x64 only. Detected architecture '$processorArchitecture'."
}
if (-not $env:LOCALAPPDATA) {
    throw 'LOCALAPPDATA is not available for the Chocolatey process user; APM cannot be installed per-user.'
}
if (-not (Test-Path -LiteralPath $archivePath -PathType Leaf)) {
    throw "The embedded APM release archive was not found: $archivePath"
}

$installRoot = Join-Path $env:LOCALAPPDATA 'Programs\apm'
$releasesRoot = Join-Path $installRoot 'releases'
$releaseDir = Join-Path $releasesRoot "chocolatey-$packageVersion"
$binDir = Join-Path $installRoot 'bin'
$currentDir = Join-Path $installRoot 'current'
$shimPath = Join-Path $binDir 'apm.cmd'
$stagingRoot = Join-Path $env:TEMP ("apm-cli-" + [Guid]::NewGuid().ToString('N'))
$stagedRelease = "$releaseDir.new-" + [Guid]::NewGuid().ToString('N')
$backupRelease = $null
$newCurrentDir = "$currentDir.new-" + [Guid]::NewGuid().ToString('N')
$oldCurrentDir = $null

# Installation mirrors the approach used by https://github.com/microsoft/apm/blob/main/install.ps1
# with the intention that it should be compatible with apm self updating
if (Test-Path -LiteralPath $releaseDir) {
    $existingMarker = Join-Path $releaseDir 'apm-cli-chocolatey.version'
    if (-not (Test-Path -LiteralPath $existingMarker -PathType Leaf) -or
        (Get-Content -LiteralPath $existingMarker -Raw).Trim() -ne $packageVersion) {
        throw "Refusing to overwrite an APM release not owned by this package: $releaseDir"
    }
}

try {
    New-Item -ItemType Directory -Force -Path $stagingRoot, $releasesRoot, $binDir | Out-Null
    Get-ChocolateyUnzip -FileFullPath $archivePath -Destination $stagingRoot

    $bundleDir = Join-Path $stagingRoot 'apm-windows-x86_64'
    if (-not (Test-Path -LiteralPath (Join-Path $bundleDir 'apm.exe') -PathType Leaf)) {
        throw 'The APM archive did not contain the expected apm-windows-x86_64\apm.exe.'
    }

    Move-Item -LiteralPath $bundleDir -Destination $stagedRelease
    Set-Content -LiteralPath (Join-Path $stagedRelease 'apm-cli-chocolatey.version') -Value $packageVersion -Encoding ASCII

    if (Test-Path -LiteralPath $releaseDir) {
        $backupRelease = "$releaseDir.old-" + [Guid]::NewGuid().ToString('N')
        Move-Item -LiteralPath $releaseDir -Destination $backupRelease
    }
    try {
        Move-Item -LiteralPath $stagedRelease -Destination $releaseDir
    } catch {
        if ($backupRelease -and (Test-Path -LiteralPath $backupRelease) -and -not (Test-Path -LiteralPath $releaseDir)) {
            Move-Item -LiteralPath $backupRelease -Destination $releaseDir
        }
        throw
    }

    New-Item -ItemType Junction -Path $newCurrentDir -Target $releaseDir | Out-Null
    if (Test-Path -LiteralPath $currentDir) {
        $currentItem = Get-Item -LiteralPath $currentDir -Force
        if (-not $currentItem.PSIsContainer -or
            ($currentItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0) {
            throw "Refusing to replace non-junction path: $currentDir"
        }
        $currentMarker = Join-Path $currentDir 'apm-cli-chocolatey.version'
        if (-not (Test-Path -LiteralPath $currentMarker -PathType Leaf)) {
            throw "An APM installation not managed by this Chocolatey package already uses $currentDir. Remove it before installing apm-cli."
        }
        $oldCurrentDir = "$currentDir.old-" + [Guid]::NewGuid().ToString('N')
        Move-Item -LiteralPath $currentDir -Destination $oldCurrentDir
    }
    try {
        Move-Item -LiteralPath $newCurrentDir -Destination $currentDir
    } catch {
        if ($oldCurrentDir -and (Test-Path -LiteralPath $oldCurrentDir) -and -not (Test-Path -LiteralPath $currentDir)) {
            Move-Item -LiteralPath $oldCurrentDir -Destination $currentDir
        }
        throw
    }

    if ($oldCurrentDir -and (Test-Path -LiteralPath $oldCurrentDir)) {
        [IO.Directory]::Delete($oldCurrentDir)
    }
    if ($backupRelease -and (Test-Path -LiteralPath $backupRelease)) {
        Remove-Item -LiteralPath $backupRelease -Recurse -Force
    }

    $shimContent = "@echo off`r`nREM Generated by the apm-cli Chocolatey package.`r`n`"%LOCALAPPDATA%\Programs\apm\current\apm.exe`" %*`r`nexit /b %ERRORLEVEL%`r`n"
    Set-Content -LiteralPath $shimPath -Value $shimContent -Encoding ASCII -NoNewline
    Install-ChocolateyPath -PathToInstall $binDir -PathType User
    Install-ChocolateyPath -PathToInstall $currentDir -PathType User
} finally {
    if (Test-Path -LiteralPath $stagingRoot) {
        Remove-Item -LiteralPath $stagingRoot -Recurse -Force
    }
    if (Test-Path -LiteralPath $stagedRelease) {
        Remove-Item -LiteralPath $stagedRelease -Recurse -Force
    }
    if ($newCurrentDir -and (Test-Path -LiteralPath $newCurrentDir)) {
        [IO.Directory]::Delete($newCurrentDir)
    }
}
